import test from 'node:test';
import assert from 'node:assert/strict';
import { Window } from 'happy-dom';
import { createCanvas } from '@napi-rs/canvas';

test('planner integration: startup, numeric edits, undo, mode switch, room rebuild and persistence', async () => {
  // DOM and canvas test doubles exercise application wiring without claiming browser/WebGL QA.
  const dom = new Window({url:'http://127.0.0.1:5173/'});
  for(const key of ['window','document','navigator','HTMLElement','HTMLCanvasElement','Element','Node','Event','MouseEvent','KeyboardEvent','ResizeObserver','localStorage','FormData','AbortController']) {
    Object.defineProperty(globalThis,key,{configurable:true,writable:true,value:key==='window'?dom:(dom as any)[key]});
  }
  const canvases=new WeakMap<object,ReturnType<typeof createCanvas>>();
  dom.HTMLCanvasElement.prototype.getContext=function(type: string) {
    if(type!=='2d') return null;
    if(!canvases.has(this)) canvases.set(this,createCanvas(this.width || 300,this.height || 150));
    return canvases.get(this)!.getContext('2d') as any;
  } as any;
  dom.document.body.innerHTML='<div id="app"></div>';
  const {NullEngine}=await import('@babylonjs/core');
  const {Planner}=await import('../src/planner');
  const {freshConfig}=await import('../src/config/office');
  const legacy:any=freshConfig();
  legacy.room.openings[0]={id:'window',kind:'window',wall:'south',offset:.8,width:1.3,height:1.1,sill:1.05,confirmed:false};
  legacy.room.beams=[{id:'ceiling-beam',enabled:false,wall:'north',offset:0,length:3.8,projection:.4,drop:.4}];
  legacy.room.cornerFeatures=[{id:'corner-feature',enabled:false,corner:'north-west',width:.2,depth:.2,height:2.65}];
  const legacyJSON=JSON.stringify(legacy);
  dom.localStorage.setItem('roomwork.office.v3',legacyJSON);
  const engine=new NullEngine(); engine.runRenderLoop=()=>{};
  const planner=new Planner(()=>engine);
  const button=(selector:string)=>{const element=dom.document.querySelector(selector); assert.ok(element,selector); (element as any).click();};
  const field=(selector:string,value:string)=>{
    const input=dom.document.querySelector(selector) as any; assert.ok(input,selector); input.value=value; input.dispatchEvent(new dom.Event('change',{bubbles:true}));
  };
  const saved=()=>JSON.parse(dom.localStorage.getItem('roomwork.office.v4')!);
  try {
    assert.equal(dom.localStorage.getItem('roomwork.office.v3'),legacyJSON,'Original browser save remains intact');
    assert.equal(saved().room.openings[0].wall,'south','Old browser save gets the requested correction');
    assert.equal(saved().room.openings[0].width,.95); assert.equal(saved().room.beams.length,2);
    assert.equal(dom.document.querySelector('.object-title h2')!.textContent,'L-shaped corner desk');
    assert.equal(dom.document.querySelectorAll('.object-row').length,7);
    assert.equal(dom.document.querySelectorAll('i[data-lucide]').length,0,'Lucide placeholders should have been replaced');
    button('[data-select="chair"]');
    field('[data-group="position"][data-field="x"]','-0.40');
    assert.equal(saved().furniture.find((f:any)=>f.id==='chair').position.x,-.4);
    button('[data-action="undo"]'); assert.equal(saved().furniture.find((f:any)=>f.id==='chair').position.x,-.55);
    button('[data-action="redo"]'); assert.equal(saved().furniture.find((f:any)=>f.id==='chair').position.x,-.4);
    const gizmo=(planner as any).gizmos.gizmos.positionGizmo;
    gizmo.onDragStartObservable.notifyObservers({});
    (planner as any).furniture.get('chair').root.position.x=-.35;
    gizmo.onDragEndObservable.notifyObservers({});
    assert.equal(saved().furniture.find((f:any)=>f.id==='chair').position.x,-.35,'Gizmo drag commits to centralized state');
    dom.document.querySelector('#scene-canvas')!.dispatchEvent(new dom.KeyboardEvent('keydown',{code:'ArrowRight',bubbles:true}));
    assert.ok(Math.abs(saved().furniture.find((f:any)=>f.id==='chair').position.x+.3)<1e-8,'Arrow keys nudge the selected object');
    assert.ok(!(planner as any).navigation.edit.inputs.attached.keyboard,'Arrow keys must not also orbit the camera');
    field('[data-group="dimensions"][data-field="width"]','10');
    assert.equal(saved().furniture.find((f:any)=>f.id==='chair').dimensions.width,.64);
    assert.match(dom.document.querySelector('#toast')!.textContent!,/outside the room/);
    button('[data-mode="walk"]'); assert.ok(dom.document.querySelector('#app')!.classList.contains('walking'));
    assert.ok(!(dom.document.querySelector('#walk-overlay') as any).hidden);
    const navigation=(planner as any).navigation, scene=(planner as any).scene;
    scene.render();
    assert.equal(scene.activeCamera,navigation.walk);
    const beforeWalk=navigation.walk.position.x;
    Object.defineProperty(dom.document,'pointerLockElement',{configurable:true,value:dom.document.querySelector('#scene-canvas')});
    dom.document.dispatchEvent(new dom.Event('pointerlockchange'));
    engine.getDeltaTime=()=>16;
    dom.dispatchEvent(new dom.KeyboardEvent('keydown',{code:'KeyW'}));
    scene.render(); scene.render();
    dom.dispatchEvent(new dom.KeyboardEvent('keyup',{code:'KeyW'}));
    assert.ok(Number.isFinite(navigation.walk.position.x) && navigation.walk.position.x<beforeWalk,'Actual walking frames must move the Babylon camera without corrupting it');
    assert.ok(Array.from(navigation.walk.getViewMatrix().m).every(n=>Number.isFinite(n)));
    assert.ok(scene.getActiveMeshes().length>0,'Room geometry must remain in view after walking');
    Object.defineProperty(dom.document,'pointerLockElement',{configurable:true,value:null});
    dom.document.dispatchEvent(new dom.Event('pointerlockchange'));
    button('[data-mode="edit"]'); assert.ok(!dom.document.querySelector('#app')!.classList.contains('walking'));
    button('[data-select="desk"]'); field('[data-group="dimensions"][data-field="height"]','0.80');
    assert.equal(saved().furniture.find((f:any)=>f.id==='monitor-left').position.y,1.12,'Desk height must not move wall-mounted displays');
    field('[data-group="position"][data-field="z"]','-0.30');
    assert.equal(saved().furniture.find((f:any)=>f.id==='desk').position.z,-.17,'Moving into the corner step must be rejected');
    assert.match(dom.document.querySelector('#toast')!.textContent!,/corner step/);
    field('[data-group="cornerDesk"][data-field="worktopDepth"]','0.75');
    assert.equal(saved().furniture.find((f:any)=>f.id==='desk').cornerDesk.worktopDepth,.75);
    button('[data-action="rotate"]'); assert.equal(dom.document.querySelector('[data-tool="rotate"]')!.getAttribute('aria-pressed'),'true');
    button('[data-select="monitor-left"]');
    field('[data-group="wallMount"][data-field="maxReach"]','0.10');
    assert.equal(saved().furniture.find((f:any)=>f.id==='monitor-left').monitor.wallMount.maxReach,.65);
    assert.match(dom.document.querySelector('#toast')!.textContent!,/wall arm reach/);
    field('[data-group="wallMount"][data-field="offset"]','-0.73');
    assert.equal(saved().furniture.find((f:any)=>f.id==='monitor-left').monitor.wallMount.offset,-.73);
    button('[data-action="settings"]');
    const form=dom.document.querySelector('#room-form')!;
    (form.querySelector('[name="height"]') as any).value='2.70';
    (form.querySelector('[name="led.color"]') as any).value='#44aaff';
    (form.querySelector('[name="opening.0.detail.frameColor"]') as any).value='#625347';
    (form.querySelector('[name="opening.0.detail.housingHeight"]') as any).value='0.25';
    (form.querySelector('[name="opening.0.detail.slatPitch"]') as any).value='0.04';
    form.dispatchEvent(new dom.Event('submit',{bubbles:true,cancelable:true}));
    assert.equal(dom.document.querySelector('#settings-error')!.textContent,'','Room settings should apply without errors');
    assert.equal(saved().room.height,2.7); assert.equal(saved().room.beams[0].enabled,true);
    assert.equal(saved().room.baseboardLED.color,'#44aaff');
    assert.equal((planner as any).baseboards.material.emissiveColor.toHexString(),'#44AAFF');
    assert.equal(saved().room.cornerFeatures[0].enabled,true);
    assert.equal(saved().room.openings[0].windowDetail.housingHeight,.25);
    assert.equal(saved().room.openings[0].windowDetail.slatPitch,.04);
    assert.equal((planner as any).materials.windowFrames.window.diffuseColor.toHexString(),'#625347');
    button('[data-action="undo"]'); assert.equal(saved().room.baseboardLED.color,'#ff3030');
    button('[data-action="redo"]'); assert.equal(saved().room.baseboardLED.color,'#44aaff');
    button('[data-visibility="desk"]'); assert.equal(saved().furniture.find((f:any)=>f.id==='desk').visible,false);
    // Exercise a scene frame: world matrices, active camera, shadows and gizmo setup.
    (planner as any).scene.render();
  } finally { planner.dispose(); await dom.happyDOM.close(); }
});
